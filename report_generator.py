from datetime import datetime


def generate_report(
    document_name,
    risk_result,
    risks,
    compliance_result,
    mismatches
):
    """
    Generate a text-based DocRisk AI analysis report.
    """

    report = []

    report.append("=" * 60)
    report.append("              DocRisk AI")
    report.append("       DOCUMENT RISK ANALYSIS REPORT")
    report.append("=" * 60)

    report.append(f"\nDocument: {document_name}")
    report.append(
        f"Analysis Date: {datetime.now().strftime('%d-%m-%Y %H:%M')}"
    )

    # Risk Summary
    report.append("\n" + "-" * 60)
    report.append("RISK SUMMARY")
    report.append("-" * 60)

    report.append(
        f"Risk Score : {risk_result['score']}/100"
    )
    report.append(
        f"Risk Level : {risk_result['level']}"
    )

    # Detected Risks
    report.append("\n" + "-" * 60)
    report.append("DETECTED RISKS")
    report.append("-" * 60)

    if risks:
        for risk in risks:
            report.append(
                f"⚠ {risk['type']} - {risk['severity']}"
            )
    else:
        report.append("No major risks detected.")

    # Compliance
    report.append("\n" + "-" * 60)
    report.append("COMPLIANCE ANALYSIS")
    report.append("-" * 60)

    documents = compliance_result.get("documents", [])

    if documents:
        report.append("\nRequired Documents:")

        for item in documents:
            status = item["status"]

            symbol = "✓" if status == "FOUND" else "✗"

            report.append(
                f"{symbol} {item['document']} - {status}"
            )

    fields = compliance_result.get("fields", [])

    if fields:
        report.append("\nRequired Information:")

        for item in fields:
            status = item["status"]

            symbol = "✓" if status == "FOUND" else "✗"

            report.append(
                f"{symbol} {item['field']} - {status}"
            )

    # Missing Documents
    missing_documents = compliance_result.get(
        "missing_documents",
        []
    )

    if missing_documents:

        report.append("\nMissing Documents:")

        for document in missing_documents:
            report.append(f"✗ {document}")

    # Missing Fields
    missing_fields = compliance_result.get(
        "missing_fields",
        []
    )

    if missing_fields:

        report.append("\nMissing Information:")

        for field in missing_fields:
            report.append(f"✗ {field}")

    # Mismatches
    report.append("\n" + "-" * 60)
    report.append("MISMATCH ANALYSIS")
    report.append("-" * 60)

    if mismatches:

        for item in mismatches:

            report.append(
                f"\nField: {item['field']}"
            )

            report.append(
                f"Expected: {item['expected']}"
            )

            report.append(
                f"Found: {item['actual']}"
            )

            report.append(
                f"Status: {item['status']}"
            )

    else:
        report.append("No mismatches detected.")

    # Final Recommendation
    report.append("\n" + "-" * 60)
    report.append("RECOMMENDATION")
    report.append("-" * 60)

    level = risk_result["level"]

    if level == "HIGH":
        recommendation = (
            "Carefully verify this document before proceeding."
        )

    elif level == "MEDIUM":
        recommendation = (
            "Review the detected issues and missing information."
        )

    else:
        recommendation = (
            "The document appears relatively safe, "
            "but normal verification is recommended."
        )

    report.append(recommendation)

    report.append("\n" + "=" * 60)
    report.append("Generated by DocRisk AI")
    report.append("=" * 60)

    return "\n".join(report)